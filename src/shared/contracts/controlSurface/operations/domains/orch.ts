import * as z from 'zod'
import { hasForbiddenControlCharacter, orchestrationTextSchema } from '../../../dto/orchestration'
import { defineOperation } from '../defineOperation'

const id = z.string().trim().min(1)
const label = z
  .string()
  .trim()
  .min(1)
  .max(256)
  .refine(
    value => !hasForbiddenControlCharacter(value) && !/[\r\n\t]/.test(value),
    'Control characters are refused',
  )
const requestId = z.uuid().describe('Idempotency key generated by the CLI per invocation')
const dispatchId = z.uuid().describe('Dispatch identifier generated by the CLI per invocation')
const executorTarget = label.describe('Executor node title or identifier')
const forceFlag = z.boolean().optional().describe('Close even with a dispatch in flight')

export const orchSpawnOperation = defineOperation({
  id: 'orch.spawn',
  kind: 'command',
  scope: 'interact',
  availability: 'always',
  summary: 'Create an executor node linked to the calling orchestrator',
  errors: [
    'orch.forbidden',
    'orch.link_invalid',
    'orch.executor_unavailable',
    'orch.limit_reached',
    'orch.protocol_mismatch',
  ],
  input: z.strictObject({
    requestId,
    provider: z.enum(['codex']).describe('Executor provider; only codex in phase 2'),
    prompt: orchestrationTextSchema.optional().describe('Initial task sent as the first dispatch'),
    title: label.optional().describe('Title of the new executor node'),
    model: label.optional().describe('Model identifier passed to the executor provider'),
    orchestratorNodeId: id.optional().describe('Orchestrator node; accepted from the user only'),
  }),
})

export const orchDispatchOperation = defineOperation({
  id: 'orch.dispatch',
  kind: 'command',
  scope: 'interact',
  availability: 'always',
  summary: 'Queue a task for a linked executor',
  errors: [
    'orch.forbidden',
    'orch.not_linked',
    'orch.executor_unavailable',
    'orch.round_limit_reached',
    'orch.dispatch_conflict',
  ],
  input: z.strictObject({
    dispatchId,
    to: executorTarget,
    text: orchestrationTextSchema.describe('Task text, 1..32768 UTF-8 bytes, tab and newline only'),
    deadlineMs: z
      .number()
      .int()
      .min(1000)
      .max(86_400_000)
      .optional()
      .describe('Deadline in milliseconds after acceptance; default 30 minutes'),
    fresh: z.boolean().optional().describe('Start a fresh executor session for this dispatch'),
    allowRepeat: z.boolean().optional().describe('Allow the same text again within 10 minutes'),
  }),
})

export const orchStatusOperation = defineOperation({
  id: 'orch.status',
  kind: 'query',
  scope: 'interact',
  availability: 'always',
  summary: 'Show executor links with health, rounds, queue and pending approvals',
  errors: ['orch.forbidden', 'orch.not_linked'],
  input: z.strictObject({ to: executorTarget.optional() }),
})

export const orchCancelOperation = defineOperation({
  id: 'orch.cancel',
  kind: 'command',
  scope: 'interact',
  availability: 'always',
  summary: 'Cancel a queued dispatch',
  errors: ['orch.forbidden', 'orch.not_linked', 'orch.dispatch_in_flight'],
  input: z.strictObject({ dispatchId }),
})

export const orchInterruptOperation = defineOperation({
  id: 'orch.interrupt',
  kind: 'command',
  scope: 'interact',
  availability: 'always',
  summary: 'Interrupt the running turn of a linked executor',
  errors: ['orch.forbidden', 'orch.not_linked', 'orch.executor_unavailable'],
  input: z.strictObject({ to: executorTarget }),
})

export const orchCloseOperation = defineOperation({
  id: 'orch.close',
  kind: 'command',
  scope: 'interact',
  availability: 'always',
  summary: 'Close the link to an executor and shut its service down',
  errors: ['orch.forbidden', 'orch.not_linked', 'orch.dispatch_in_flight'],
  input: z.strictObject({ to: executorTarget, force: forceFlag }),
})

export const orchLinkCreateOperation = defineOperation({
  id: 'orch.link.create',
  kind: 'command',
  scope: 'admin',
  availability: 'always',
  summary: 'Link an existing executor node to an orchestrator node',
  errors: [
    'orch.forbidden',
    'orch.link_invalid',
    'orch.executor_unavailable',
    'orch.limit_reached',
  ],
  input: z.strictObject({
    orchestratorNodeId: id.describe('Orchestrator node that will dispatch work'),
    executorNodeId: id.describe('Executor node that will run the work'),
  }),
})

export const orchLinkCloseOperation = defineOperation({
  id: 'orch.link.close',
  kind: 'command',
  scope: 'admin',
  availability: 'always',
  summary: 'Close a link by identifier',
  errors: ['orch.forbidden', 'orch.not_linked', 'orch.dispatch_in_flight'],
  input: z.strictObject({ linkId: z.uuid().describe('Link identifier'), force: forceFlag }),
})

export const orchLinkListOperation = defineOperation({
  id: 'orch.link.list',
  kind: 'query',
  scope: 'read',
  availability: 'always',
  summary: 'List orchestration links with the links revision',
  errors: ['orch.forbidden'],
  input: z.strictObject({ projectId: id.optional().describe('Restrict the list to one project') }),
})

export const orchLinkExtendOperation = defineOperation({
  id: 'orch.link.extend',
  kind: 'command',
  scope: 'admin',
  availability: 'always',
  summary: 'Grant extra dispatch rounds to a link',
  errors: ['orch.forbidden', 'orch.not_linked'],
  input: z.strictObject({
    linkId: z.uuid().describe('Link identifier'),
    rounds: z.number().int().min(1).max(2).describe('Extra rounds to grant, 1 or 2'),
    reason: label.describe('Why the user extends the limit'),
  }),
})

export const orchApprovalRespondOperation = defineOperation({
  id: 'orch.approval.respond',
  kind: 'command',
  scope: 'admin',
  availability: 'always',
  summary: 'Answer a pending executor approval request',
  errors: ['orch.forbidden', 'orch.not_linked', 'orch.approval_not_found'],
  input: z.strictObject({
    executorNodeId: id.describe('Executor node holding the request'),
    requestId: id.describe('Approval request identifier'),
    decision: z
      .enum(['accept', 'acceptForSession', 'decline', 'cancel'])
      .describe('Decision sent to the executor'),
  }),
})

export const orchHooksApproveOperation = defineOperation({
  id: 'orch.hooks.approve',
  kind: 'command',
  scope: 'admin',
  availability: 'always',
  summary: 'Approve pending executor hooks and restart its service',
  errors: ['orch.forbidden', 'orch.not_linked', 'orch.executor_unavailable'],
  input: z.strictObject({
    executorNodeId: id.describe('Executor node with pending hooks'),
    keys: z.array(id).min(1).max(64).describe('Hook keys to approve'),
  }),
})

export const orchOperations = [
  orchSpawnOperation,
  orchDispatchOperation,
  orchStatusOperation,
  orchCancelOperation,
  orchInterruptOperation,
  orchCloseOperation,
  orchLinkCreateOperation,
  orchLinkCloseOperation,
  orchLinkListOperation,
  orchLinkExtendOperation,
  orchApprovalRespondOperation,
  orchHooksApproveOperation,
] as const
